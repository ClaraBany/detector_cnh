"""## 4. Carregar a imagem (arquivo, URL ou base64)

A função `carregar_imagem` aceita **três tipos de entrada** e descobre sozinha qual é:

| Entrada | Exemplo |
|---|---|
| Caminho de arquivo | `"fotos/gato.jpg"` |
| URL | `"https://site.com/foto.jpg"` |
| Texto em base64 | `"iVBORw0KGgo..."` ou `"data:image/png;base64,iVBORw0..."` |

Ela sempre devolve a imagem como um **array NumPy em RGB** (altura x largura x 3 canais).

> Por que RGB? O OpenCV costuma trabalhar em BGR, e isso causa confusão de cores. Aqui padronizamos tudo em RGB logo na entrada.
"""

def eh_url(texto):
    return texto.lower().startswith(("http://", "https://"))


def carregar_imagem(fonte):
    """
    Recebe um caminho de arquivo, uma URL ou uma string base64.
    Devolve a imagem como array NumPy em RGB.
    """
    # Caso 1: bytes crus (útil quando virar API e a imagem chegar como upload)
    if isinstance(fonte, (bytes, bytearray)):
        dados = bytes(fonte)

    elif isinstance(fonte, str):
        fonte = fonte.strip()

        # Caso 2: URL
        if eh_url(fonte):
            resposta = requests.get(fonte, timeout=15, headers={"User-Agent": "Mozilla/5.0"})
            resposta.raise_for_status()
            dados = resposta.content

        # Caso 3: caminho de arquivo que existe no computador
        elif os.path.exists(fonte):
            with open(fonte, "rb") as arquivo:
                dados = arquivo.read()

        # Caso 4: base64 (com ou sem o prefixo "data:image/...;base64,")
        else:
            if fonte.startswith("data:"):
                fonte = fonte.split(",", 1)[1]
            fonte = re.sub(r"\s+", "", fonte)  # remove espaços e quebras de linha
            try:
                dados = base64.b64decode(fonte, validate=True)
            except Exception:
                raise ValueError(
                    "Não consegui interpretar a entrada. "
                    "Envie um caminho de arquivo válido, uma URL ou uma imagem em base64."
                )
    else:
        raise TypeError("A fonte da imagem deve ser texto (caminho, URL, base64) ou bytes.")

    imagem = Image.open(io.BytesIO(dados)).convert("RGB")
    return np.array(imagem)

"""## 5. Detector do OpenCV (OPCIONAL)

Alguns projetos precisam **achar** o objeto antes de classificar. Exemplo: em uma foto de grupo, primeiro achamos cada rosto e depois classificamos cada rosto separadamente (emoção, pessoa, etc).

O OpenCV já vem com detectores prontos chamados **Haar Cascades**. Se o seu projeto **não** precisa disso, deixe `USAR_DETECTOR_OPENCV = False` e a imagem inteira será usada.

A função `detectar_regioes` sempre devolve uma **lista de regiões**:
- com detector desligado: uma região, que é a imagem toda;
- com detector ligado: uma região para cada rosto (ou objeto) encontrado.

Assim, o resto do código funciona igual nos dois casos.
"""

ARQUIVOS_DETECTORES = {
    "rosto": "haarcascade_frontalface_default.xml",
    "olhos": "haarcascade_eye.xml",
    "corpo": "haarcascade_fullbody.xml",
}

detector = None
if USAR_DETECTOR_OPENCV:
    caminho_xml = os.path.join(cv2.data.haarcascades, ARQUIVOS_DETECTORES[TIPO_DETECTOR])
    detector = cv2.CascadeClassifier(caminho_xml)
    if detector.empty():
        raise RuntimeError(f"Não consegui carregar o detector em: {caminho_xml}")
    print(f"Detector '{TIPO_DETECTOR}' carregado.")
else:
    print("Detector OpenCV desligado: a imagem inteira será usada.")


def detectar_regioes(imagem_rgb):
    """
    Devolve uma lista de regiões. Cada região é um dicionário com:
      - "caixa": (x, y, largura, altura) no formato da imagem original
      - "recorte": o pedaço da imagem dentro da caixa
    """
    altura_img, largura_img = imagem_rgb.shape[:2]

    # Sem detector: a "região" é a imagem toda
    if detector is None:
        return [{"caixa": (0, 0, largura_img, altura_img), "recorte": imagem_rgb}]

    # Com detector: o Haar Cascade trabalha melhor em tons de cinza
    cinza = cv2.cvtColor(imagem_rgb, cv2.COLOR_RGB2GRAY)
    caixas = detector.detectMultiScale(
        cinza,
        scaleFactor=1.1,   # quanto a imagem é reduzida a cada passada (menor = mais lento e mais preciso)
        minNeighbors=5,    # quanto maior, menos falsos positivos
        minSize=(30, 30),  # ignora detecções menores que isso
    )

    regioes = []
    for (x, y, largura, altura) in caixas:
        regioes.append({
            "caixa": (int(x), int(y), int(largura), int(altura)),
            "recorte": imagem_rgb[y:y + altura, x:x + largura],
        })
    return regioes

