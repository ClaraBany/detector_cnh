def converter_imagem_para_extracao(imagem_rgb):
    '''Converte o array RGB do notebook para o formato que a sua extração espera.'''
    if FORMATO_IMAGEM_EXTRACAO == "numpy_rgb":
        return imagem_rgb
    if FORMATO_IMAGEM_EXTRACAO == "pil":
        return Image.fromarray(np.ascontiguousarray(imagem_rgb))
    if FORMATO_IMAGEM_EXTRACAO == "numpy_bgr":
        return cv2.cvtColor(imagem_rgb, cv2.COLOR_RGB2BGR)
    raise ValueError("FORMATO_IMAGEM_EXTRACAO deve ser 'numpy_rgb', 'pil' ou 'numpy_bgr'.")


def extrair_features_para_modelo(imagem_rgb):
    '''Converte a imagem para o formato da extração, extrai as features e seleciona
    apenas as colunas usadas pelo modelo (a seleção só acontece se a validação estiver
    ligada e houver NOMES_FEATURES).'''
