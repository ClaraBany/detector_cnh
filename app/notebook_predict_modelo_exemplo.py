"""## 11. Como isso vira uma API

Se você seguiu a estrutura acima, o trabalho já está quase pronto. Na API, as etapas são as mesmas e só muda **quem chama** a função `prever`:

| No notebook | Na API |
|---|---|
| `CAMINHO_MODELO`, `MAPA_CLASSES`... | variáveis de configuração do serviço |
| `joblib.load(...)` | roda **uma vez** quando a API inicia |
| `prever(fonte)` | roda a **cada requisição** |
| `print(resultado)` | a API devolve `resultado` como JSON |

O que já deixamos preparado:

- `carregar_imagem` aceita `bytes`, para receber upload de arquivo.
- `prever` devolve só tipos básicos do Python (dicionários, listas, textos, números), que viram JSON sem problemas.
- A lógica está separada em funções pequenas, fáceis de copiar para um arquivo `.py`.

Na API, vamos precisar de uma rota (por exemplo `POST /predict`) que recebe `{"imagem": "<url ou base64>"}`, chama `prever(...)` e devolve o dicionário.
"""